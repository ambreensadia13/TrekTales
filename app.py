def get_secret(name: str, default=None):
    """
    Safely read a Streamlit secret.

    Priority:
    1. Streamlit secrets
    2. Default value
    """

    try:
        value = st.secrets.get(name)

        if value is not None and str(value).strip():
            return value

    except Exception:
        pass

    return default


