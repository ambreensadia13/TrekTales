def clean_text(value):
    """
    Remove accidental HTML/code-fence artifacts while preserving
    Markdown content generated by the AI.
    """

    if value is None:
        return ""

    text = str(value)

    # Remove code fences only.
    text = re.sub(
        r"```(?:markdown|md|text)?",
        "",
        text,
        flags=re.IGNORECASE,
    )

    text = text.replace("```", "")

    # Remove common HTML tags.
    text = re.sub(
        r"<\s*/?\s*(p|div|span|br|strong|b|em|i|section|article|ul|ol|li|h1|h2|h3|h4|h5|h6)[^>]*>",
        "",
        text,
        flags=re.IGNORECASE,
    )

    # Remove accidental HTML comments.
    text = re.sub(
        r"<!--.*?-->",
        "",
        text,
        flags=re.DOTALL,
    )

    return text.strip()


def normalize_evidence(evidence):
    """
    Normalize retrieved FAISS evidence into a list of dictionaries.
    """

    if evidence is None:
        return []

    if isinstance(evidence, dict):

        for key in (
            "results",
            "documents",
            "items",
            "matches",
            "evidence",
        ):

            if isinstance(evidence.get(key), list):
                evidence = evidence[key]
                break

        else:
            evidence = [evidence]

    if not isinstance(evidence, (list, tuple)):
        evidence = [evidence]

    normalized = []

    for item in evidence:

        if item is None:
            continue

        if isinstance(item, str):

            text = item.strip()

            if text:
                normalized.append(
                    {
                        "text": text,
                        "source": "Unknown",
                    }
                )

            continue

        if isinstance(item, dict):

            metadata = item.get("metadata")

            if not isinstance(metadata, dict):
                metadata = {}

            text = (
                item.get("text")
                or item.get("content")
                or item.get("chunk")
                or item.get("document")
                or metadata.get("text")
                or metadata.get("content")
                or ""
            )

            source = (
                item.get("source")
                or item.get("filename")
                or item.get("file")
                or metadata.get("source")
                or metadata.get("filename")
                or metadata.get("file")
                or "Unknown"
            )

            page = (
                item.get("page")
                or metadata.get("page")
                or ""
            )

            if text:

                normalized.append(
                    {
                        "text": str(text).strip(),
                        "source": str(source).strip(),
                        "page": str(page).strip(),
                    }
                )

    return normalized


def format_source_name(source):
    """
    Make source names clean for UI display.
    """

    if not source:
        return "Unknown"

    source = str(source)

    source = source.replace("\\", "/")

    source = source.split("/")[-1]

    source = source.replace(".html", "")
    source = source.replace(".htm", "")

    return source.strip()


def source_list(evidence):
    """
    Extract unique source filenames.
    """

    sources = []

    for item in normalize_evidence(evidence):

        source = format_source_name(
            item.get("source", "")
        )

        if source and source != "Unknown":
            sources.append(source)

    return list(dict.fromkeys(sources))


